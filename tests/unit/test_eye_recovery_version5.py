"""Generic eye model version 5 (zero-start laws), harness 7 and additive evaluation 5
(synthetic data)."""

from __future__ import annotations

import math
from collections.abc import Mapping
from dataclasses import dataclass, field, replace
from typing import Any

import numpy as np
import pytest

from peykar.model_learning import eye_recovery_population2 as version2
from peykar.model_learning import eye_recovery_population5 as version5
from peykar.validation import eye_additive_evaluation as additive1
from peykar.validation import eye_additive_evaluation4 as additive4
from peykar.validation import eye_additive_evaluation5 as additive5
from peykar.validation import eye_recovery_evaluation6 as harness6
from peykar.validation import eye_recovery_evaluation7 as harness7
from peykar_core.errors import InvalidRequest

DAY = 1.0 / 30.4375
MONTHS = (3.0, 6.0, 12.0, 24.0)
COMMON: dict[str, Any] = {
    "model_id": "m",
    "model_version": "v",
    "quantity": "axial length change",
    "covariate_reference": math.exp(24.5),
    "covariate_unit": "pseudo-reference exp(AL0 / 1 mm)",
    "transient_months": None,
    "penalty_modes": (0.1, 0.1, 0.5),
    "robust_sd": (0.3, 0.3, 2.0),
    "study_effects": "per_group",
    "forecast_noise_pooling": "pooled",
}
ZERO: dict[str, Any] = {**COMMON, "penalty_modes": (0.1, 0.5), "robust_sd": (0.3, 2.0)}
# Initial rate (mm per year) and time constant (months) per context.
CONTEXTS = {
    "human/single_vision": (0.36, 48.0),
    "human/atropine": (0.26, 48.0),
    "human/orthokeratology": (0.18, 60.0),
}
SCALE = additive1.AdditiveScale(
    quantity="axial length", unit="mm", model_unit=1.0, covariate_unit=1.0, report_unit=0.01
)
STRIPPED = {"generic_model_version", "start", "law", "rate_months"}


@dataclass(frozen=True)
class Series:
    series_id: str
    study_id: str
    context: str
    reference_value: float
    months: tuple[float, ...]
    fractions: tuple[float, ...]
    aggregate_n: int | None = None
    role: str = "control"
    metadata: Mapping[str, Any] = field(default_factory=dict)

    @property
    def kind(self) -> str:
        return "aggregate" if self.aggregate_n is not None else "individual"

    @property
    def is_aggregate(self) -> bool:
        return self.aggregate_n is not None

    def prefix(self, last: float) -> Series:
        keep = [i for i, m in enumerate(self.months) if m <= last]
        return replace(
            self,
            months=tuple(self.months[i] for i in keep),
            fractions=tuple(self.fractions[i] for i in keep),
        )


def _synthetic(seed: int = 4) -> list[Series]:
    """Three studies per context and two group means per study, generated by the
    zero-rate law with a rate slope of 0.05 mm/year per mm of baseline axial length."""
    rng = np.random.default_rng(seed)
    out = []
    for c, (context, (rate, tau)) in enumerate(sorted(CONTEXTS.items())):
        for s in range(3):
            study = f"st-{c}-{s}"
            shift = rng.normal(0.0, 0.02)
            for k in range(2):
                axial = float(rng.uniform(23.5, 25.5))
                v = rate + shift + 0.05 * (axial - 24.5)
                t = np.asarray(MONTHS)
                change = v * (tau / 12.0) * (1.0 - np.exp(-(t - DAY) / tau))
                values = np.exp(change + rng.normal(0.0, 0.01, t.size))
                out.append(
                    Series(
                        series_id=f"{study}/{k}",
                        study_id=study,
                        context=context,
                        reference_value=math.exp(axial),
                        months=MONTHS,
                        fractions=tuple(float(x) for x in values),
                        aggregate_n=60,
                    )
                )
    return out


def test_configuration_and_laws() -> None:
    free = version5.RecoveryConfig(**COMMON)
    level = version5.RecoveryConfig(**ZERO, start="zero_level")
    rate = version5.RecoveryConfig(**ZERO, start="zero_rate", rate_months=12.0)
    assert free.parameters == version2.RecoveryConfig(**COMMON).parameters
    assert level.parameters == ("level", "log_tau_months") and level.dimensions == 2
    assert rate.parameters == ("initial_rate", "log_tau_months") and rate.linear == 1
    described = rate.describe()
    assert described["generic_model_version"] == "5.0.0" and described["start"] == "zero_rate"
    assert described["rate_months"] == 12.0 and level.describe()["rate_months"] is None
    # Unchanged at t1; the rate law rises at v per R months and levels off at v tau / R.
    tau = 48.0
    for config, theta in ((level, (1.2, math.log(tau))), (rate, (0.3, math.log(tau)))):
        assert version5.law_fraction(config, [DAY], parameters=theta)[0] == 1.0
    early = version5.law_fraction(rate, [DAY + 1e-3], parameters=(0.3, math.log(tau)))[0]
    assert math.log(early) / 1e-3 == pytest.approx(0.3 / 12.0, rel=1e-3)
    late = version5.law_fraction(rate, [5000.0], parameters=(0.3, math.log(tau)))[0]
    assert math.log(late) == pytest.approx(0.3 * tau / 12.0, rel=1e-6)
    same = version5.law_fraction(level, [12.0], parameters=(0.3 * tau / 12.0, math.log(tau)))
    assert same == pytest.approx(
        version5.law_fraction(rate, [12.0], parameters=(0.3, math.log(tau)))
    )
    for bad in (
        {**ZERO, "start": "late"},
        {**ZERO, "start": "zero_rate", "rate_months": 0.0},
        {**ZERO, "start": "zero_level", "transient_months": 7 * DAY},
        {**COMMON, "start": "zero_level"},
    ):
        with pytest.raises(InvalidRequest):
            version5.RecoveryConfig(**bad)


def test_free_start_reproduces_version_2() -> None:
    series = _synthetic()
    two = version2.fit_population(version2.RecoveryConfig(**COMMON), series)
    five_config = version5.RecoveryConfig(**COMMON)
    five = version5.fit_population(five_config, series)
    a, b = two.families["human/all"], five.families["human/all"]
    np.testing.assert_array_equal(a.solution, b.solution)
    np.testing.assert_array_equal(a.covariance, b.covariance)
    assert a.objective == b.objective
    assert dict(two.noise_centers.centers) == dict(five.noise_centers.centers)
    item = series[0]
    prior = two.prior(item.context, item.kind, 0.3)
    other = five.prior(item.context, item.kind, 0.3)
    np.testing.assert_array_equal(prior["mean"], other["mean"])
    np.testing.assert_array_equal(prior["covariance"], other["covariance"])
    gaussian = version2.gaussian(prior["mean"], prior["covariance"])
    noise = two.noise(item.kind, item.context, item.aggregate_n)
    old = version2.predictive(
        two.config,
        version2.posterior(two.config, gaussian, series=item.prefix(6.0), noise=noise),
        months=[12.0, 24.0],
    )
    new = version5.predictive(
        five_config,
        version5.posterior(five_config, gaussian, series=item.prefix(6.0), noise=noise),
        months=[12.0, 24.0],
    )
    assert old == new
    described = five.describe()
    assert {k: v for k, v in described.items() if k not in STRIPPED} == {
        k: v for k, v in two.describe().items() if k not in STRIPPED
    }


def test_zero_rate_fit_recovers_the_population() -> None:
    series = _synthetic()
    config = version5.RecoveryConfig(**ZERO, start="zero_rate", rate_months=12.0)
    fit = version5.fit_population(config, series)
    assert isinstance(fit, version5.RecoveryFit)
    family = fit.families["human/all"]
    assert family.fixed[2] == pytest.approx(0.05, abs=0.03)  # rate slope on AL0
    rates = {c: fit.location(c, 0.0)[0][0] for c in CONTEXTS}
    for context, (rate, _) in CONTEXTS.items():
        assert rates[context] == pytest.approx(rate, abs=0.03)
    assert rates["human/single_vision"] > rates["human/atropine"] > rates["human/orthokeratology"]
    prior = fit.prior("human/single_vision", "aggregate", 0.0)
    initial = version5.predictive(
        config,
        version5.posterior(
            config,
            version5.gaussian(prior["mean"], prior["covariance"]),
            series=None,
            noise=fit.noise("aggregate", "human/single_vision", 60),
        ),
        months=[1.0, 12.0],
    )
    expected = 0.36 * 4.0 * (1.0 - math.exp(-(12.0 - DAY) / 48.0))
    assert math.log(initial["point_fraction"][1]) == pytest.approx(expected, abs=0.03)
    assert abs(math.log(initial["point_fraction"][0])) < 0.05
    described = fit.describe()["families"]["human/all"]
    assert set(described["mean"]["parameters"]) == {"initial_rate", "log_tau_months"}
    assert described["first_parameter_slope_on_covariate"] == pytest.approx(family.fixed[2])


def _strip(report: dict[str, Any]) -> dict[str, Any]:
    def study(item: dict[str, Any]) -> dict[str, Any]:
        fit = item["population_fit"]
        return {
            **item,
            "evaluation_version": None,
            "additive_evaluation_version": None,
            "population_fit": {k: v for k, v in fit.items() if k not in STRIPPED},
        }

    return {
        **report,
        "evaluation_version": None,
        "harness_version": None,
        "model_configuration": None,
        "studies": [study(s) for s in report["studies"]],
    }


def test_harness_7_with_a_free_start_equals_harness_6() -> None:
    series = _synthetic()
    six = harness6.leave_one_study_out(
        version2.RecoveryConfig(**COMMON), series, studies=["st-0-0"]
    )
    seven = harness7.leave_one_study_out(
        version5.RecoveryConfig(**COMMON), series, studies=["st-0-0"]
    )
    assert seven["evaluation_version"] == "7.0.0"
    assert _strip(six) == _strip(seven)


def test_additive_evaluation_5_dispatch() -> None:
    series = _synthetic()
    old = version2.RecoveryConfig(**COMMON)
    four = additive4.leave_one_study_out(old, series, scale=SCALE, studies=["st-1-0"])
    five = additive5.leave_one_study_out(old, series, scale=SCALE, studies=["st-1-0"])
    assert five["harness_version"] == four["harness_version"] == "6.0.0"
    assert five["studies"][0]["additive_evaluation_version"] == "5.0.0"
    assert _strip(four) == _strip(five)
    zero = version5.RecoveryConfig(**ZERO, start="zero_rate", rate_months=12.0)
    report = additive5.leave_one_study_out(zero, series, scale=SCALE, studies=["st-1-0"])
    assert report["harness_version"] == "7.0.0"
    assert report["studies"][0]["population_fit"]["start"] == "zero_rate"
    rows = report["studies"][0]["next_observation"][0]["rows"]
    assert all(math.isfinite(r["predictions"]["population_assimilation"]) for r in rows)
